import { writeFile } from 'node:fs/promises';

const libraryId = process.env.BUNNY_STREAM_LIBRARY_ID;
const apiKey = process.env.BUNNY_STREAM_API_KEY;
const cdnHostname = process.env.BUNNY_STREAM_CDN_HOSTNAME;

if (!libraryId || !apiKey || !cdnHostname) {
  throw new Error('Set BUNNY_STREAM_LIBRARY_ID, BUNNY_STREAM_API_KEY, and BUNNY_STREAM_CDN_HOSTNAME before syncing.');
}

const response = await fetch(`https://video.bunnycdn.com/library/${libraryId}/videos?page=1&itemsPerPage=1000&orderBy=date`, {
  headers: { AccessKey: apiKey },
});

if (!response.ok) {
  throw new Error(`Bunny Stream returned ${response.status} ${response.statusText}`);
}

const payload = await response.json();
const videos = (payload.items ?? payload).map((video) => ({
  id: video.guid,
  title: video.title,
  name: video.title.replace(/\.[^.]+$/, ''),
  status: video.status,
  ready: video.encodeProgress === 100,
  embed: `https://iframe.mediadelivery.net/embed/${libraryId}/${video.guid}`,
  poster: `https://${cdnHostname}/${video.guid}/thumbnail.jpg`,
}));

const output = `// Generated by sync-bunny-videos.mjs. No private API key is stored here.\nwindow.BUNNY_MEDIA = ${JSON.stringify(videos, null, 2)};\n`;
await writeFile(new URL('./bunny-media.js', import.meta.url), output, 'utf8');
console.log(`Synced ${videos.length} Bunny Stream videos (${videos.filter((video) => video.ready).length} fully encoded).`);
